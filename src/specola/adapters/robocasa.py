"""
adapters/robocasa.py — RoboCasa / RoboSuite SimulatorAdapter
============================================================

RoboCasa-specific specialization of MujocoAdapter.

This module defines only behavior that depends on RoboCasa or RoboSuite:

- declaration-driven object-entity discovery (``env.object_cfgs``);
- declaration-backed task roles (packaged role table, ``entity_roles``/
  ``entity_role_basis``/``entity_role_provenance``, namespaced ``role:*``
  property tags);
- RoboSuite gripper-site conventions;
- object-category labels;
- fixture-region discovery;
- gripper joint, force, and torque properties;
- RoboCasa environment construction and registry integration.

Generic MuJoCo body, site, joint, pose, velocity, and scalar property
extraction remains in adapters/mujoco.py.
"""

