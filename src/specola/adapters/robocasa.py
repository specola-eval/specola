def _generative_textures_setting() -> Optional[str]:
    import os

    value = os.environ.get("ROBOCASA_GENERATIVE_TEXTURES", "")
    if value in ("", "0", "false", "no", "none", "None"):
        return None
    if value == "100p":
        return "100p"
    raise ValueError(
        "ROBOCASA_GENERATIVE_TEXTURES must be '100p' or unset, "
        "got {!r}".format(value)
    )


def _make_robocasa(
    task: Optional[str],
    robot: Optional[str],
    target_only: bool,
    capture_frames: bool = True,
    seed: Optional[int] = None,
) -> RoboCasaAdapter:
    """
    Registry factory. ``capture_frames=False`` builds the env without an
    offscreen renderer, for a run that captures no camera frame.

    ``seed`` reaches ``robosuite.make``, where RoboCasa's ``Kitchen`` seeds
    the generator it draws the layout, style, textures and objects from.
    ``None`` draws from OS entropy, a new kitchen per construction.
    """
    import os

    try:
        import robocasa  # noqa: F401
        import robosuite
    except ImportError as exc:
        raise ImportError(
            "RoboCasa and RoboSuite are required for the "
            "'robocasa' adapter."
        ) from exc

    task_name = (
        task
        or os.environ.get(
            "ROBOCASA_TASK",
            "PickPlaceCounterToCabinet",
        )
    )

    robot_name = (
        robot
        or os.environ.get(
            "ROBOCASA_ROBOT",
            "PandaOmron",
        )
    )

    def _make(offscreen: bool):
        return robosuite.make(
            task_name,
            robots=[robot_name],
            has_renderer=False,
            # True lets robosuite build its offscreen render context
            # inside reset, where RoboCasa's style randomization uploads
            # textures through it. A context created any later samples
            # stale texture data (green robot, wrong-colored fixtures) —
            # capture_frame renders through this live context.
            has_offscreen_renderer=offscreen,
            use_camera_obs=False,
            ignore_done=True,
            camera_names=[],
            # "100p" swaps the flat robosuite materials for RoboCasa's
            # AI-generated kitchen textures (visual only; opt-in so
            # recorded frames stay comparable across runs unless asked).
            # RoboCasa asserts on anything but None/"100p", so validate
            # here for a readable error instead of a bare AssertionError.
            generative_textures=_generative_textures_setting(),
            seed=seed,
        )

    if not capture_frames:
        environment = _make(offscreen=False)
        environment.reset()
        return RoboCasaAdapter(environment, target_only=target_only)

    # The render context must exist from construction whenever a frame may
    # be captured (see the comment in _make). Monitoring must not require
    # GL, so failure degrades to the rendererless env.
    environment = None
    try:
        environment = _make(offscreen=True)
        # The simulator must already have an active state before the
        # adapter performs its discovery reset.
        environment.reset()
    except Exception as exc:
        # Expected cause: no GL on this machine — monitoring must not
        # require a renderer, so retry rendererless (camera capture
        # degrades to stale textures or nothing). Surface the original
        # error: a non-GL failure (bad task, scene-gen bug) will fail
        # the retry too, and this line is what names the real cause.
        print(
            "  Web warning: offscreen-renderer construction failed "
            "({}: {}); retrying without it.".format(
                type(exc).__name__, exc),
            file=sys.stderr,
        )
        try:
            if environment is not None:
                environment.close()
        except Exception:
            pass
        environment = _make(offscreen=False)
        environment.reset()

    return RoboCasaAdapter(
        environment,
        target_only=target_only,
    )


def _handles(obj) -> bool:
    """Cheap module-path sniff — never imports RoboCasa/RoboSuite."""
    return (type(obj).__module__ or "").startswith("robocasa")


def _wrap(env, **kwargs) -> RoboCasaAdapter:
    """Wrap an existing RoboCasa / RoboSuite env.

    Adapter kwargs pass through, e.g. ``target_only=`` to restrict region
    discovery to the task's target cabinet.
    """
    return RoboCasaAdapter(env, **kwargs)


