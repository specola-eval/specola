class RoboCasaAdapter(MujocoAdapter):
    """
    MuJoCo adapter specialized for RoboCasa and RoboSuite.

    Parameters
    ----------
    env:
        Constructed RoboCasa / RoboSuite environment.

    body_rules:
        Optional replacement for the default RoboCasa body rules.

    regions:
        Explicit region definitions. When supplied, automatic fixture-region
        discovery is skipped by MujocoAdapter.

    gripper_site:
        Explicit RoboSuite gripper site. When omitted, the adapter searches
        the default site names.

    perception_gate:
        Optional ``(entity_state, env) -> bool`` filter.

    target_only:
        When true, automatically discover only the task's target cabinet
        regions. When false, discover regions from all available fixtures.

    Field availability is global to the shared MuJoCo mechanism. Every
    curated joint family present on the live binding is exposed eagerly.
    """

    def __init__(
        self,
        env: Any,
        body_rules: Optional[Sequence[BodyRule]] = None,
        regions: Optional[Sequence[RegionSpec]] = None,
        gripper_site: Optional[str] = None,
        perception_gate: Optional[
            Callable[[EntityState, Any], bool]
        ] = None,
        target_only: bool = False,
        **legacy_options: Any,
    ) -> None:
        self.target_only = bool(target_only)

        # Populated during every adapter reset by _build_labels().
        self._object_categories: Dict[str, str] = {}

        # Declaration-backed task roles, rebuilt each reset by
        # _build_labels(). Missing attribute, empty dict, and
        # entity-not-in-dict all mean "no declared role".
        self.entity_roles: Dict[int, str] = {}
        self.entity_role_basis: Dict[int, str] = {}
        self.entity_role_provenance: Dict[int, str] = {}
        self.entity_declared_names: Dict[int, str] = {}
        self.entity_declared_categories: Dict[int, str] = {}
        self.entity_declaration_sources: Dict[int, str] = {}
        self.entity_fixture_names: Dict[int, Tuple[str, ...]] = {}
        self.entity_fixture_refs: Dict[int, Tuple[str, ...]] = {}
        self.entity_fixture_types: Dict[int, str] = {}
        self.entity_fixture_provenance: Dict[int, str] = {}
        self._fixture_by_root: Dict[str, Any] = {}
        self._fixture_root_by_entity: Dict[int, str] = {}
        self.entity_task_refs: Dict[int, Tuple[str, ...]] = {}
        self._contact_identity_by_body: Dict[int, Tuple[str, ...]] = {}
        self.entity_region_fixture_names: Dict[int, Tuple[str, ...]] = {}
        self.entity_region_fixture_refs: Dict[int, Tuple[str, ...]] = {}
        self.entity_region_keys: Dict[int, str] = {}
        self._region_declarations: Dict[
            str, Tuple[Tuple[str, ...], Tuple[str, ...], str]
        ] = {}

        # Contact body ownership, rebuilt each reset alongside the
        # roles: body ID -> role of the declared object whose compiled
        # subtree owns that body (nearest object-main ancestor).
        self._contact_role_by_body: Dict[int, str] = {}

        super().__init__(
            env=env,
            body_rules=body_rules,
            regions=regions,
            gripper_site=gripper_site,
            gripper_class="gripper",
            perception_gate=perception_gate,
            **legacy_options,
        )

    # ------------------------------------------------------------------
    # Adapter capability metadata
    # ------------------------------------------------------------------

    @property
    def supported_classes(self) -> FrozenSet[str]:
        """
        Classes this configured adapter can emit.

        Custom body rules and explicit region classes are included
        automatically.
        """
        classes = {
            rule.cls
            for rule in self.body_rules
        }

        classes.add(self.gripper_class)

        # Synthetic entity carrying sensors with no resolvable body/site
        # owner (see adapters/mujoco.py). Any reset that produces an
        # orphan sensor must not be rejected by a closed vocabulary that
        # omits this class.
        classes.add(_ORPHAN_SENSOR_ENTITY_CLASS)

        # Synthetic entity carrying actuators with no resolvable body
        # owner (see adapters/mujoco.py). Any reset that produces an
        # orphan actuator must not be rejected by a closed vocabulary
        # that omits this class.
        classes.add(_ORPHAN_ACTUATOR_ENTITY_CLASS)
        classes.update(_CURATED_FIELD_OWNER_ENTITY_CLASSES)

        if self.regions:
            classes.update(
                region.cls
                for region in self.regions
            )
        else:
            classes.add("region")

        return frozenset(classes)

    # ------------------------------------------------------------------
    # RoboCasa naming conventions
    # ------------------------------------------------------------------

    def _default_body_rules(
        self,
    ) -> Sequence[BodyRule]:
        """Robot rule plus declaration-driven object rules.

        Each declared object cfg contributes its expected compiled body
        ``f"{name}_main"``; exactly those bodies become object-class
        entities. Rebuilt at every policy rebuild (adapter reset), so
        the entity population follows the episode's declarations. No
        compiled-name heuristic remains.
        """
        expected = frozenset(
            "{}_main".format(name)
            for name in self._declared_object_names()
        )
        fixture_roots = frozenset(
            root for _fixture, _names, _refs, root
            in self._normalized_fixtures()
        )
        rules = list(_DEFAULT_BODY_RULES)
        # Task fixture identity comes from env.fixture_refs. One exact
        # compiled root represents the full articulated fixture subtree.
        rules.append(
            BodyRule(
                match=lambda name, _roots=fixture_roots: name in _roots,
                cls="fixture",
                priority=5,
                joint_scope="subtree",
            )
        )
        # Appended even when no object is declared so "object" stays in
        # the supported-class vocabulary.
        rules.append(
            BodyRule(
                match=lambda name, _expected=expected: name in _expected,
                cls="object",
                priority=10,
                joint_scope="body",
            )
        )
        return rules

    def _normalized_fixture_refs(
        self,
    ) -> List[Tuple[Any, Tuple[str, ...], str]]:
        """Return unique ``(fixture, aliases, root_body)`` declarations.

        RoboCasa stores generated refs as ``(fixture, full_depth_region)``
        and replayed refs as bare fixtures. Aliases are merged by exact
        compiled root; one fixture instance claiming two roots fails.
        """
        refs = getattr(self.env, "fixture_refs", None)
        if not refs:
            return []
        if not isinstance(refs, Mapping):
            raise RoboCasaRoleError(
                "RoboCasa fixture_refs must be a mapping"
            )

        by_root: Dict[str, Tuple[Any, List[str]]] = {}
        root_by_identity: Dict[int, str] = {}
        for raw_alias, raw_value in refs.items():
            alias = str(raw_alias)
            fixture = (
                raw_value[0]
                if isinstance(raw_value, tuple)
                else raw_value
            )
            root = getattr(fixture, "root_body", None)
            if not alias or fixture is None or not root:
                raise RoboCasaRoleError(
                    "RoboCasa fixture ref {!r} has no fixture with an "
                    "exact root_body".format(raw_alias)
                )
            root = str(root)
            fixture_identity = id(fixture)
            previous_root = root_by_identity.get(fixture_identity)
            if previous_root is not None and previous_root != root:
                raise RoboCasaRoleError(
                    "RoboCasa fixture ref {!r} changed root body from "
                    "{!r} to {!r}".format(
                        alias, previous_root, root
                    )
                )
            root_by_identity[fixture_identity] = root
            if root in by_root:
                if by_root[root][0] is not fixture:
                    raise RoboCasaRoleError(
                        "RoboCasa fixture refs assign root body {!r} to "
                        "distinct fixture instances".format(root)
                    )
                by_root[root][1].append(alias)
            else:
                by_root[root] = (fixture, [alias])

        return [
            (fixture, tuple(aliases), root)
            for root, (fixture, aliases) in by_root.items()
        ]

    def _normalized_fixtures(
        self,
    ) -> List[Tuple[Any, Tuple[str, ...], Tuple[str, ...], str]]:
        """Return exact scene fixtures with separate task-ref aliases."""
        fixtures = getattr(self.env, "fixtures", None)
        if fixtures is None:
            fixture_items = ()
        elif isinstance(fixtures, Mapping):
            fixture_items = fixtures.items()
        else:
            fixture_items = (
                (
                    getattr(fixture, "name", "fixture_{}".format(index)),
                    fixture,
                )
                for index, fixture in enumerate(fixtures)
            )

        by_root: Dict[str, Tuple[Any, List[str], List[str]]] = {}
        root_by_identity: Dict[int, str] = {}
        for raw_name, fixture in fixture_items:
            root = getattr(fixture, "root_body", None)
            if fixture is None or not root:
                raise RoboCasaRoleError(
                    "RoboCasa scene fixture {!r} has no exact "
                    "root_body".format(raw_name)
                )
            root = str(root)
            name = str(raw_name)
            fixture_identity = id(fixture)
            previous_root = root_by_identity.get(fixture_identity)
            if previous_root is not None and previous_root != root:
                raise RoboCasaRoleError(
                    "RoboCasa scene fixture {!r} changed root body from "
                    "{!r} to {!r}".format(
                        name, previous_root, root
                    )
                )
            root_by_identity[fixture_identity] = root
            if root in by_root:
                if by_root[root][0] is not fixture:
                    raise RoboCasaRoleError(
                        "RoboCasa scene fixtures assign root body {!r} "
                        "to distinct fixture instances".format(root)
                    )
                by_root[root][1].append(name)
            else:
                by_root[root] = (fixture, [name], [])

        for fixture, aliases, root in self._normalized_fixture_refs():
            fixture_identity = id(fixture)
            previous_root = root_by_identity.get(fixture_identity)
            if previous_root is not None and previous_root != root:
                raise RoboCasaRoleError(
                    "RoboCasa fixture ref changed a scene fixture root "
                    "body from {!r} to {!r}".format(
                        previous_root, root
                    )
                )
            root_by_identity[fixture_identity] = root
            if root in by_root:
                if by_root[root][0] is not fixture:
                    raise RoboCasaRoleError(
                        "RoboCasa scene fixtures and fixture refs assign "
                        "root body {!r} to distinct fixture instances"
                        .format(root)
                    )
                by_root[root][2].extend(aliases)
            else:
                by_root[root] = (fixture, [], list(aliases))

        return [
            (fixture, tuple(names), tuple(refs), root)
            for root, (fixture, names, refs) in by_root.items()
        ]

    # ------------------------------------------------------------------
    # Declaration-backed task roles
    # ------------------------------------------------------------------

    def _declared_object_names(self) -> List[str]:
        """Declared object cfg names, in declaration order.

        Fails loudly on an unnamed or duplicated declaration: both
        break the exact-name identity the role contract rests on.
        """
        configurations = getattr(self.env, "object_cfgs", None)
        if not configurations:
            return []
        names: List[str] = []
        for index, configuration in enumerate(configurations):
            name = None
            if isinstance(configuration, Mapping):
                name = configuration.get("name")
            if not name or not isinstance(name, str):
                raise RoboCasaRoleError(
                    "RoboCasa object cfg [{}] carries no usable name; "
                    "declared identity is required for object "
                    "discovery".format(index)
                )
            if name in names:
                raise RoboCasaRoleError(
                    "RoboCasa declares the object name {!r} more than "
                    "once; declared names must be unique".format(name)
                )
            names.append(name)
        return names

    @staticmethod
    def _reconcile_object_entities(
        declared_names: Sequence[str],
        discovered_body_names: Sequence[str],
    ) -> Dict[str, str]:
        """Reconcile declarations against discovered object bodies.

        Returns ``body_name -> declared_name`` on exact agreement and
        raises with both sides named otherwise. No fallback path
        exists.
        """
        expected = {
            "{}_main".format(name): name for name in declared_names
        }
        discovered = set(discovered_body_names)
        missing = sorted(set(expected) - discovered)
        undeclared = sorted(discovered - set(expected))
        if missing or undeclared:
            parts = []
            if missing:
                parts.append(
                    "declared objects without a compiled body: {}"
                    .format(", ".join(
                        "{!r} (expected body {!r})".format(
                            expected[body], body
                        )
                        for body in missing
                    ))
                )
            if undeclared:
                parts.append(
                    "object bodies without a declaration: {}".format(
                        ", ".join(repr(body) for body in undeclared)
                    )
                )
            raise RoboCasaRoleError(
                "RoboCasa declaration/entity mismatch: " +
                "; ".join(parts)
            )
        return {body: expected[body] for body in discovered}

    def _reconcile_and_assign_roles(self) -> None:
        declared = self._declared_object_names()
        object_entities = {
            body.body_name: body.entity_id
            for body in self._bodies
            if body.entity_class == "object"
        }
        mapping = self._reconcile_object_entities(
            declared, list(object_entities)
        )
        entry = task_role_entry(type(self.env).__name__)
        roles: Dict[int, str] = {}
        bases: Dict[int, str] = {}
        provenance: Dict[int, str] = {}
        self.entity_declared_names = {}
        self.entity_declared_categories = {}
        self.entity_declaration_sources = {}
        if entry is not None:
            table_roles = entry["roles"]
            for body_name, declared_name in mapping.items():
                entity_id = object_entities[body_name]
                self.entity_declared_names[entity_id] = declared_name
                self.entity_declaration_sources[entity_id] = (
                    "env.object_cfgs[name={!r}]".format(declared_name)
                )
                category = self._object_categories.get(body_name)
                if category is not None:
                    self.entity_declared_categories[entity_id] = category
                info = table_roles.get(declared_name)
                if info is not None:
                    roles[entity_id] = info["role"]
                    bases[entity_id] = info["basis"]
                    provenance[entity_id] = info["provenance"]
        else:
            for body_name, declared_name in mapping.items():
                entity_id = object_entities[body_name]
                self.entity_declared_names[entity_id] = declared_name
                self.entity_declaration_sources[entity_id] = (
                    "env.object_cfgs[name={!r}]".format(declared_name)
                )
                category = self._object_categories.get(body_name)
                if category is not None:
                    self.entity_declared_categories[entity_id] = category
        self.entity_roles = roles
        self.entity_role_basis = bases
        self.entity_role_provenance = provenance
        self._contact_role_by_body = self._build_contact_ownership(
            roles
        )

    def _reconcile_fixture_entities(self) -> None:
        """Attach fixture declaration identity to exact root entities."""
        declared = {
            root: (fixture, names, refs)
            for fixture, names, refs, root in self._normalized_fixtures()
        }
        entities = {
            body.body_name: body.entity_id
            for body in self._bodies
            if body.entity_class == "fixture"
        }
        missing = sorted(set(declared) - set(entities))
        undeclared = sorted(set(entities) - set(declared))
        if missing or undeclared:
            raise RoboCasaRoleError(
                "RoboCasa fixture declaration/entity mismatch: "
                "missing roots {}; undeclared roots {}".format(
                    missing, undeclared
                )
            )

        self.entity_fixture_names = {}
        self.entity_fixture_refs = {}
        self.entity_fixture_types = {}
        self.entity_fixture_provenance = {}
        self._fixture_by_root = {
            root: fixture for root, (fixture, _, _) in declared.items()
        }
        self._fixture_root_by_entity = {
            entities[root]: root for root in declared
        }
        # Task-parameter fixture identity: atomic kitchen tasks name
        # their target fixture through a plain env attribute rather than
        # env.fixture_refs (only the drawer tasks populate refs). The
        # audited attribute set mirrors the 11-task X15 population's
        # predicates; identity is matched on the exact fixture object.
        self.entity_task_refs = {}
        entity_by_fixture_identity = {
            id(fixture): entities[root]
            for root, (fixture, _, _) in declared.items()
        }
        for attr in _TASK_FIXTURE_ATTRS:
            entity_id = entity_by_fixture_identity.get(
                id(getattr(self.env, attr, None))
            )
            if entity_id is not None:
                self.entity_task_refs[entity_id] = (
                    self.entity_task_refs.get(entity_id, ()) + (attr,)
                )
        for root, (fixture, names, refs) in declared.items():
            entity_id = entities[root]
            self.entity_fixture_names[entity_id] = names
            self.entity_fixture_refs[entity_id] = refs
            self.entity_fixture_types[entity_id] = type(fixture).__name__
            self.entity_fixture_provenance[entity_id] = (
                "env.fixtures[{}]; env.fixture_refs[{}] -> "
                "root_body {!r}".format(
                    ", ".join(repr(name) for name in names) or "none",
                    ", ".join(repr(alias) for alias in refs) or "none",
                    root,
                )
            )
            self.entity_declaration_sources[entity_id] = (
                "env.fixtures"
                if not refs
                else "env.fixtures + env.fixture_refs"
            )

    def _build_contact_ownership(
        self,
        roles: Mapping[int, str],
    ) -> Dict[int, str]:
        """Body ID -> role over each role-carrying object's subtree.

        Contact rows attribute force to whichever body a geom belongs
        to, not necessarily the object's main body, so every body in
        the compiled subtree rooted at a declared object's
        ``<name>_main`` body maps to that object's role. Ownership is
        by body ID and MJCF parent structure only; body names are
        never parsed.
        """
        main_roles: Dict[int, str] = {}
        for body in self._bodies:
            if body.entity_id in roles:
                main_roles[body.body_id] = roles[body.entity_id]
        if not main_roles:
            return {}
        parentid = np.asarray(
            self._model.body_parentid
        ).astype(int).tolist()
        return _body_roles_by_ancestry(parentid, main_roles)

    def _build_contact_identity(self) -> None:
        """Body ID -> identity tags over each tagged entity's subtree.

        Contact pairs inherit the same identity namespaces entities
        carry (``declared_name:*``, ``task_ref:*``, ``fixture_ref:*``),
        expanded over compiled subtrees by the same nearest-ancestor
        rule as role ownership, so a spec can select "contacts involving
        the task's counter" without naming scene bodies. ``role:*``
        stays on its existing path.
        """
        body_id_by_name = {
            body.body_name: body.body_id for body in self._bodies
        }
        main: Dict[int, Tuple[str, ...]] = {}

        def _add(body_id: Optional[int], tag: str) -> None:
            if body_id is not None:
                main[body_id] = main.get(body_id, ()) + (tag,)

        for body in self._bodies:
            declared = self.entity_declared_names.get(body.entity_id)
            if declared is not None:
                _add(body.body_id, "declared_name:" + declared)
        for entity_id, root in self._fixture_root_by_entity.items():
            for ref in self.entity_task_refs.get(entity_id, ()):
                _add(body_id_by_name.get(root), "task_ref:" + ref)
            for ref in self.entity_fixture_refs.get(entity_id, ()):
                _add(body_id_by_name.get(root), "fixture_ref:" + ref)

        if not main:
            self._contact_identity_by_body = {}
            return
        parentid = np.asarray(
            self._model.body_parentid
        ).astype(int).tolist()
        self._contact_identity_by_body = _body_roles_by_ancestry(
            parentid, main
        )

    def _contact_tag_vocabulary(self) -> FrozenSet[str]:
        """Possible contact-pair tags under the RoboCasa role policy.

        The closed role vocabulary of the roles design record plus
        ``role:robot``, plus every identity tag the reset-time scene
        declares (``declared_name:*``, ``task_ref:*``,
        ``fixture_ref:*``) — exactly the values ``_contact_pair_tags``
        can emit. Declared in capabilities so a filtered contact
        selector validates at compilation while the pair population is
        still empty.
        """
        identity = {
            tag
            for tags in getattr(
                self, "_contact_identity_by_body", {}
            ).values()
            for tag in tags
        }
        return frozenset(
            _ROLE_TAG_PREFIX + role
            for role in (
                "target",
                "distractor",
                "container",
                "auxiliary",
                "robot",
            )
        ) | identity

    def _contact_pair_tags(
        self,
        body_pair: Tuple[int, int],
    ) -> Tuple[str, ...]:
        """Declaration-backed ``role:*`` tags for one contact pair.

        Each participant body contributes its owning declared object's
        role (via the reset-built ownership map) or ``role:robot`` when
        it belongs to the robot; fixture and unresolved bodies
        contribute nothing.
        """
        tags = set()
        for body_id in body_pair:
            if body_id in self._robot_body_ids:
                tags.add(_ROLE_TAG_PREFIX + "robot")
            role = self._contact_role_by_body.get(body_id)
            if role is not None:
                tags.add(_ROLE_TAG_PREFIX + role)
            tags.update(
                getattr(
                    self, "_contact_identity_by_body", {}
                ).get(body_id, ())
            )
        return tuple(sorted(tags))

    def _body_properties(
        self,
        entity_id: int,
        body_name: str,
        body_id: int,
        joint_ids: Sequence[int],
    ) -> Dict[str, float]:
        """Add declaration-tier fixture-state signals.

        RoboCasa fixtures with press-button logic (Microwave,
        CoffeeMachine) keep their on/off state as a Python flag the env
        flips in ``update_state`` — it exists nowhere in MjData. The
        native success criteria read that flag, so it is exposed here as
        a discrete 0/1 signal with fixture-flag provenance rather than
        silently proxied by a physical quantity. Read-only: the flag is
        never written from this path.
        """
        properties = super()._body_properties(
            entity_id,
            body_name,
            body_id,
            joint_ids,
        )
        fixture = self._fixture_by_root.get(body_name)
        if fixture is not None:
            properties.update(self._fixture_state_signals(fixture))
        return properties

    def _fixture_state_signals(self, fixture: Any) -> Dict[str, float]:
        """Declaration-tier state signals for one scene fixture.

        Two families, both read-only transcriptions of the fixture's own
        state helpers (the quantities the native success criteria
        consume):

        - ``state_turned_on``: the press-button ``_turned_on`` flag
          (Microwave, CoffeeMachine) as 0/1 — exists nowhere in MjData.
        - ``state_door_fraction_<door>``: ``get_door_state`` normalized
          open fractions. The normalization constant (e.g. a Drawer's
          ``0.55 * depth``) is scene geometry the raw ``qpos`` keys
          cannot carry, same physical-anchor pattern as the X14
          ``flexedge_length0`` parameters.

        A fixture whose helper cannot resolve its joints in this scene
        contributes nothing — availability is what the scene offers, and
        the helper raising for absent joints is a scene fact, not an
        error.
        """
        signals: Dict[str, float] = {}
        flag = getattr(fixture, "_turned_on", None)
        if isinstance(flag, bool):
            signals["state_turned_on"] = float(flag)
        door_state = getattr(fixture, "get_door_state", None)
        if callable(door_state):
            try:
                doors = door_state(self.env)
            except Exception:
                doors = {}
            for door_name, fraction in doors.items():
                if isinstance(fraction, (int, float)):
                    signals[
                        "state_door_fraction_{}".format(door_name)
                    ] = float(fraction)
        return signals

    def _task_knob_joint(self) -> Optional[str]:
        """Joint name of the episode's task-sampled stove knob, if any.

        ``ManipulateStoveKnob`` tasks draw ``env.knob`` (a burner
        location) per episode; the fixture ref identifies the stove but
        not the knob. The joint name follows the fixture's own naming
        rule (``fixtures/stove.py``: ``{prefix}knob_{loc}_joint``).
        """
        knob = getattr(self.env, "knob", None)
        stove = getattr(self.env, "stove", None)
        if not isinstance(knob, str) or stove is None:
            return None
        prefix = getattr(stove, "naming_prefix", None)
        if not isinstance(prefix, str) or not prefix:
            return None
        return "{}knob_{}_joint".format(prefix, knob)

    def _entity_extra_tags(self, entity_id: int) -> Tuple[str, ...]:
        tags = set()
        role = self.entity_roles.get(entity_id)
        if role is not None:
            tags.add(_ROLE_TAG_PREFIX + role)
        declared_name = self.entity_declared_names.get(entity_id)
        if declared_name is not None:
            tags.add("declared_name:" + declared_name)
        category = self.entity_declared_categories.get(entity_id)
        if category is not None:
            tags.add("declared_category:" + category)
        for name in self.entity_fixture_names.get(entity_id, ()):
            tags.add("fixture_name:" + name)
        for ref in self.entity_fixture_refs.get(entity_id, ()):
            tags.add("fixture_ref:" + ref)
        for ref in self.entity_task_refs.get(entity_id, ()):
            tags.add("task_ref:" + ref)
        region_key = self.entity_region_keys.get(entity_id)
        if region_key is not None:
            for name in self.entity_region_fixture_names.get(
                entity_id, ()
            ):
                tags.add(
                    "fixture_region_name:{}:{}".format(name, region_key)
                )
            for ref in self.entity_region_fixture_refs.get(entity_id, ()):
                tags.add(
                    "fixture_region_ref:{}:{}".format(ref, region_key)
                )
        return tuple(sorted(tags))

    def property_metadata(
        self,
        entity_id: int,
    ) -> Dict[str, PropertyMeta]:
        """Apply declaration tags to direct and eager property families."""
        metadata = super().property_metadata(entity_id)

        root = self._fixture_root_by_entity.get(entity_id)
        if root is not None:
            fixture = self._fixture_by_root.get(root)
            scope = self._metadata_extraction_scope()
            allowed = (
                scope.get("fixture", ()) if scope is not None else None
            )
            state_meta = {}
            for key in self._fixture_state_signals(fixture):
                if allowed is not None and key not in allowed:
                    continue
                state_meta[key] = PropertyMeta(
                    group="fixture state",
                    note=(
                        "0/1" if key == "state_turned_on"
                        else "fraction"
                    ),
                    tags=(
                        ("source:fixture_flag",)
                        if key == "state_turned_on"
                        else ("source:fixture_helper",)
                    ),
                )
            if state_meta:
                metadata = dict(metadata)
                metadata.update(state_meta)
            knob_joint = self._task_knob_joint()
            if knob_joint is not None:
                tagged = {
                    key: meta
                    for key, meta in metadata.items()
                    if key.endswith(knob_joint)
                }
                if tagged:
                    metadata = dict(metadata)
                    for key, meta in tagged.items():
                        metadata[key] = meta._replace(
                            tags=tuple(meta.tags) + ("task_ref:knob",)
                        )

        extra_tags = self._entity_extra_tags(entity_id)
        if not extra_tags:
            return metadata
        return {
            key: meta._replace(
                tags=tuple(meta.tags) + tuple(
                    tag for tag in extra_tags
                    if tag not in meta.tags
                )
            )
            for key, meta in metadata.items()
        }

