def _vector3(
    value: Any,
    label: str,
) -> np.ndarray:
    array = np.asarray(
        value,
        dtype=float,
    ).reshape(-1)

    if array.shape != (3,):
        raise ValueError(
            f"{label} must contain exactly three values, "
            f"got shape {array.shape}"
        )

    if not np.all(np.isfinite(array)):
        raise ValueError(
            f"{label} contains non-finite values"
        )

    return array.copy()


def _parallelepiped_world_aabb(
    *,
    p0: np.ndarray,
    px: np.ndarray,
    py: np.ndarray,
    pz: np.ndarray,
    translation: np.ndarray,
    rotation: np.ndarray,
) -> tuple[np.ndarray, np.ndarray]:
    """
    Compute the world-axis-aligned bounding box of a local parallelepiped.
    """
    edge_x = px - p0
    edge_y = py - p0
    edge_z = pz - p0

    local_vertices = np.asarray(
        [
            p0
            + x * edge_x
            + y * edge_y
            + z * edge_z
            for x in (0.0, 1.0)
            for y in (0.0, 1.0)
            for z in (0.0, 1.0)
        ],
        dtype=float,
    )

    world_vertices = (
        translation[None, :]
        + local_vertices @ rotation.T
    )

    lower = np.min(
        world_vertices,
        axis=0,
    )

    upper = np.max(
        world_vertices,
        axis=0,
    )

    center = 0.5 * (
        lower + upper
    )

    half_extents = 0.5 * (
        upper - lower
    )

    return center, half_extents


def _mujoco_quaternion_to_matrix(
    quaternion: Any,
) -> np.ndarray:
    """
    Convert a MuJoCo ``[w, x, y, z]`` quaternion to a rotation matrix.
    """
    quat = np.asarray(
        quaternion,
        dtype=float,
    ).reshape(-1)

    if quat.shape != (4,):
        raise ValueError(
            "fixture quaternion must contain four values"
        )

    if not np.all(np.isfinite(quat)):
        raise ValueError(
            "fixture quaternion contains non-finite values"
        )

    norm = float(
        np.linalg.norm(quat)
    )

    if norm <= 0.0:
        raise ValueError(
            "fixture quaternion has zero norm"
        )

    w, x, y, z = quat / norm

    return np.asarray(
        [
            [
                1.0 - 2.0 * (y * y + z * z),
                2.0 * (x * y - z * w),
                2.0 * (x * z + y * w),
            ],
            [
                2.0 * (x * y + z * w),
                1.0 - 2.0 * (x * x + z * z),
                2.0 * (y * z - x * w),
            ],
            [
                2.0 * (x * z - y * w),
                2.0 * (y * z + x * w),
                1.0 - 2.0 * (x * x + y * y),
            ],
        ],
        dtype=float,
    )


def _numeric_vector(
    value: Any,
) -> Optional[np.ndarray]:
    """
    Convert a scalar, vector, or common buffer object to a finite vector.
    """
    if value is None:
        return None

    for attribute in (
        "current",
        "latest",
        "value",
    ):
        candidate = getattr(
            value,
            attribute,
            None,
        )

        if candidate is not None:
            value = candidate
            break

    try:
        array = np.asarray(
            value,
            dtype=float,
        )
    except (
        TypeError,
        ValueError,
    ):
        return None

    if array.size == 0:
        return None

    # Some RoboSuite history buffers contain multiple rows. Use the most
    # recent sample while preserving ordinary one-dimensional vectors.
    if array.ndim > 1:
        array = array[-1]

    vector = array.reshape(-1)

    if not np.all(np.isfinite(vector)):
        return None

    return vector.copy()


def _first_available_vector(
    source: Any,
    attribute_names: Sequence[str],
) -> Optional[np.ndarray]:
    for attribute_name in attribute_names:
        vector = _numeric_vector(
            getattr(
                source,
                attribute_name,
                None,
            )
        )

        if vector is not None:
            return vector

    return None


def _add_xyz_properties(
    destination: Dict[str, float],
    prefix: str,
    values: np.ndarray,
) -> None:
    vector = np.asarray(
        values,
        dtype=float,
    ).reshape(-1)

    if vector.size < 3:
        return

    destination[f"{prefix}_x"] = float(
        vector[0]
    )
    destination[f"{prefix}_y"] = float(
        vector[1]
    )
    destination[f"{prefix}_z"] = float(
        vector[2]
    )
    destination[f"{prefix}_norm"] = float(
        np.linalg.norm(
            vector[:3]
        )
    )


def _unique_label(
    requested: str,
    used_labels: set[str],
) -> str:
    label = str(requested)

    if label not in used_labels:
        used_labels.add(label)
        return label

    index = 2

    while f"{label}_{index}" in used_labels:
        index += 1

    unique = f"{label}_{index}"
    used_labels.add(unique)
    return unique


