    def _discover_extra_regions(
        self,
    ) -> Sequence[RegionSpec]:
        """
        Discover containment regions from RoboCasa fixture metadata.

        RoboCasa fixtures commonly expose a ``_regions`` dictionary whose
        entries contain four fixture-local points:

            p0, px, py, pz

        These points define local half-extents around the entry's named
        compiled ``reg_*`` geom. The geom remains the live pose source, so
        the shared MuJoCo materializer recomputes the world-axis-aligned box
        on every observation.

        Physical fixture identity comes from ``env.fixtures`` and task
        aliases from ``env.fixture_refs``. When ``target_only=True``, only
        the task's ``env.cab`` fixture is used.
        """
        regions: List[RegionSpec] = []
        self._region_declarations = {}
        visited_fixtures: set[int] = set()
        # Semantic region names share the adapter's global entity-name
        # namespace with body, site, and geom entities.
        used_labels: set[str] = set(
            self._names("body")
        ) | set(self._names("site")) | set(self._names("geom"))

        fixtures = self._normalized_fixtures()
        if self.target_only:
            target_fixture = getattr(self.env, "cab", None)
            target_root = getattr(target_fixture, "root_body", None)
            fixtures = [
                record for record in fixtures
                if record[0] is target_fixture
                or record[3] == target_root
            ]

        for fixture, names, refs, _root in fixtures:
            aliases = refs or names
            self._append_fixture_regions(
                fixture=fixture,
                prefix=aliases[0],
                fixture_names=names,
                fixture_refs=refs,
                destination=regions,
                visited_fixtures=visited_fixtures,
                used_labels=used_labels,
            )

        return regions

    def _append_fixture_regions(
        self,
        *,
        fixture: Any,
        prefix: str,
        fixture_names: Tuple[str, ...],
        fixture_refs: Tuple[str, ...],
        destination: List[RegionSpec],
        visited_fixtures: set[int],
        used_labels: set[str],
    ) -> None:
        """Append all valid regions exposed by one fixture."""
        fixture_identity = id(fixture)

        if fixture_identity in visited_fixtures:
            return

        visited_fixtures.add(
            fixture_identity
        )

        region_mapping = getattr(
            fixture,
            "_regions",
            None,
        )

        if not isinstance(region_mapping, Mapping):
            return

        compiled_geoms = set(self._names("geom"))

        for region_name, region_data in region_mapping.items():
            if not isinstance(region_data, Mapping):
                warnings.warn(
                    f"Ignoring malformed region "
                    f"{prefix}_{region_name}: expected mapping",
                    RuntimeWarning,
                    stacklevel=2,
                )
                continue

            try:
                local_points = {
                    key: _vector3(
                        region_data[key],
                        f"{prefix}_{region_name}.{key}",
                    )
                    for key in (
                        "p0",
                        "px",
                        "py",
                        "pz",
                    )
                }

                element = region_data["elem"]
                geom_name = element.get("name")
                if not geom_name or geom_name not in compiled_geoms:
                    warnings.warn(
                        "Ignoring RoboCasa region {}_{}: exact compiled "
                        "geom {!r} is unavailable".format(
                            prefix, region_name, geom_name
                        ),
                        RuntimeWarning,
                        stacklevel=2,
                    )
                    continue

                p0 = local_points["p0"]
                half_extents = 0.5 * np.asarray(
                    [
                        np.linalg.norm(local_points["px"] - p0),
                        np.linalg.norm(local_points["py"] - p0),
                        np.linalg.norm(local_points["pz"] - p0),
                    ],
                    dtype=float,
                )

                # Do not register wholly degenerate metadata.
                if np.all(half_extents < 1.0e-6):
                    continue

                label = _unique_label(
                    f"{prefix}_{region_name}",
                    used_labels,
                )

                destination.append(
                    RegionSpec(
                        name=label,
                        source="geom",
                        source_name=str(geom_name),
                        half_extents=tuple(
                            float(value)
                            for value in half_extents
                        ),
                        cls="region",
                    )
                )
                self._region_declarations[label] = (
                    fixture_names,
                    fixture_refs,
                    str(region_name),
                )

            except (
                KeyError,
                TypeError,
                ValueError,
            ) as exc:
                warnings.warn(
                    f"Ignoring malformed RoboCasa region "
                    f"{prefix}_{region_name}: {exc}",
                    RuntimeWarning,
                    stacklevel=2,
                )

    def _fixture_world_transform(
        self,
        fixture: Any,
    ) -> tuple[np.ndarray, np.ndarray]:
        """
        Return fixture-local to world-frame translation and rotation.

        The MuJoCo body pose is preferred because it reflects the actual
        simulator state. Fixture metadata is used as a fallback.
        """
        body_names = set(
            self._names("body")
        )

        candidates = (
            getattr(
                fixture,
                "root_body",
                None,
            ),
            getattr(
                fixture,
                "name",
                None,
            ),
        )

        for candidate in candidates:
            if candidate is None:
                continue

            body_name = str(candidate)

            if body_name not in body_names:
                continue

            body_id = self._name2id(
                "body",
                body_name,
            )

            translation = np.asarray(
                self._data.body_xpos[body_id],
                dtype=float,
            ).copy()

            rotation = np.asarray(
                self._data.body_xmat[body_id],
                dtype=float,
            ).reshape(3, 3).copy()

            return translation, rotation

        position = getattr(
            fixture,
            "pos",
            None,
        )

        if position is None:
            raise ValueError(
                "fixture provides neither a resolvable "
                "MuJoCo root body nor a pos attribute"
            )

        translation = _vector3(
            position,
            "fixture position",
        )

        quaternion = getattr(
            fixture,
            "quat",
            None,
        )

        if quaternion is None:
            rotation = np.eye(
                3,
                dtype=float,
            )
        else:
            rotation = _mujoco_quaternion_to_matrix(
                quaternion
            )

        return translation, rotation

