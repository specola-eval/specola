_DEFAULT_BODY_RULES: tuple[BodyRule, ...] = (
    # The complete articulated robot is represented by its mobile base;
    # subtree exposes joints attached to descendant arm and gripper bodies.
    # robot0_base is deliberately NOT exposed: RoboCasa robots are mobile
    # manipulators, and robosuite parents that body to the world as a
    # static anchor parked at (10, 10, 0). Measured on
    # PickPlaceCounterToCabinet 2026-07-27: it sits at exactly that
    # position, is welded (body_jntnum 0) with the world as parent, and
    # so cannot move — 0.0 m over 60 steps under both zero and random
    # actions, which the weld makes a certainty rather than a sample.
    # The mobile base meanwhile stands wherever the episode placed it,
    # metres away in the kitchen; its coordinates are randomised per
    # episode and no seed is pinned, so no specific value is quoted here.
    #
    # Its subtree is a strict superset of the mobile base's (21 bodies
    # against 20), the extra body being the welded anchor itself. Because
    # that anchor carries no joints, the *joint* properties it would
    # expose duplicate the mobile base's; what it adds is its own pose,
    # ten metres from the scene. So a robot_* spec bound against it
    # cannot be satisfied by any proximity or containment predicate — a
    # separation predicate would be satisfied trivially, which is worse.
    BodyRule(
        match=lambda name: name == "mobilebase0_base",
        cls="robot",
        priority=0,
        joint_scope="subtree",
    ),

    # Object entities are declaration-driven: RoboCasaAdapter builds
    # one exact-match rule set from env.object_cfgs at each policy
    # rebuild (see _default_body_rules), so no compiled-name object
    # heuristic lives here. Design record:
    # docs/superpowers/specs/2026-07-28-robocasa-task-roles.md.
)


class RoboCasaRoleError(RuntimeError):
    """A RoboCasa declaration, role table, or reconciliation failure."""


_ROLE_TABLE_RESOURCE = "robocasa_role_table.json"
_ROLE_TABLE_SCHEMA_VERSION = 2
_ROLE_TAG_PREFIX = "role:"

# Env attributes through which atomic kitchen tasks name their target
# fixture (fixture_refs covers only the drawer tasks). Audited against
# the X15 population's _check_success sources 2026-08-13.
_TASK_FIXTURE_ATTRS = (
    "stove",
    "sink",
    "microwave",
    "coffee_machine",
    "counter",
)


@lru_cache(maxsize=1)
def _load_role_table() -> Mapping[str, Any]:
    """Load the packaged per-task declared-name -> role table.

    Generated by benchmarks/diagnostic_catalogue/robocasa_role_audit.py
    --emit-table from the audited robocasa source; pinned there by
    per-task source hashes whose drift is caught by the robocasa-marked
    audit test, independently of the per-reset reconciliation.
    """
    payload = pkgutil.get_data("specola.data", _ROLE_TABLE_RESOURCE)
    if payload is None:
        raise RoboCasaRoleError(
            "Packaged RoboCasa role table {!r} is missing from "
            "specola.data".format(_ROLE_TABLE_RESOURCE)
        )
    table = json.loads(payload.decode("utf-8"))
    if table.get("schema_version") != _ROLE_TABLE_SCHEMA_VERSION:
        raise RoboCasaRoleError(
            "RoboCasa role table schema version {!r} != supported "
            "{!r}".format(
                table.get("schema_version"), _ROLE_TABLE_SCHEMA_VERSION
            )
        )
    tasks = table.get("tasks")
    if not isinstance(tasks, Mapping) or (
        table.get("task_count") != len(tasks)
    ):
        raise RoboCasaRoleError(
            "RoboCasa role table task_count {!r} does not match its "
            "{} task entries".format(
                table.get("task_count"),
                len(tasks) if isinstance(tasks, Mapping) else "absent",
            )
        )
    return table


def task_role_entry(task_name: str) -> Optional[Mapping[str, Any]]:
    """Exact-name role-table entry for one task class, or None.

    Absence means the task was not in the audited population; every
    declared name is then unresolved and role-scoped consumers fail
    loudly for this task. No fuzzy matching exists.
    """
    return _load_role_table()["tasks"].get(task_name)


def _body_roles_by_ancestry(
    parentid: Sequence[int],
    main_roles: Mapping[int, str],
) -> Dict[int, str]:
    """Expand main-body roles over compiled subtrees by ancestry.

    ``parentid`` is indexed by body ID (MuJoCo ``body_parentid``; the
    worldbody is its own parent). Every body whose nearest ancestor —
    including itself — is a role-carrying main body inherits that
    body's role; nesting therefore resolves to the closest declared
    object.
    """
    roles: Dict[int, str] = {}
    for body_id in range(len(parentid)):
        current = body_id
        while True:
            if current in main_roles:
                roles[body_id] = main_roles[current]
                break
            parent = int(parentid[current])
            if parent == current:
                break
            current = parent
    return roles


