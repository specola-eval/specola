    def _discover_object_categories(
        self,
    ) -> Dict[str, str]:
        """
        Build ``body_name -> category`` from RoboCasa object_cfgs.

        RoboCasa commonly stores an object configuration such as:

            {
                "name": "obj",
                "info": {"cat": "bread"}
            }

        while the corresponding MuJoCo body is named ``obj_main``.
        """
        categories: Dict[str, str] = {}

        configurations = getattr(
            self.env,
            "object_cfgs",
            None,
        )

        if not configurations:
            return categories

        for configuration in configurations:
            if not isinstance(configuration, Mapping):
                continue

            configured_name = configuration.get(
                "name"
            )

            information = configuration.get(
                "info",
                {},
            )

            if not isinstance(information, Mapping):
                information = {}

            category = information.get("cat")

            if (
                not configured_name
                or not category
            ):
                continue

            body_name = str(configured_name)

            if not body_name.endswith("_main"):
                body_name = f"{body_name}_main"

            categories[body_name] = str(category)

        return categories

    def _object_category(
        self,
        body_name: str,
    ) -> Optional[str]:
        return self._object_categories.get(
            body_name
        )

