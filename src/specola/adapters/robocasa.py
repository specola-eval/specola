    def _gripper_properties(
        self,
        entity_id: int,
        site_name: str,
        site_id: int,
    ) -> Dict[str, float]:
        """
        Extract scalar gripper and end-effector properties.

        Properties are included only when the connected RoboSuite robot
        exposes the corresponding signal.
        """
        properties = super()._gripper_properties(
            entity_id,
            site_name,
            site_id,
        )

        robots = getattr(
            self.env,
            "robots",
            None,
        )

        if not robots:
            return properties

        robot = robots[0]

        self._add_gripper_joint_properties(
            properties,
            robot,
        )

        force = _first_available_vector(
            robot,
            (
                "recent_ee_force",
                "ee_force",
            ),
        )

        torque = _first_available_vector(
            robot,
            (
                "recent_ee_torque",
                "ee_torque",
            ),
        )

        if force is None or torque is None:
            force_torque = _first_available_vector(
                robot,
                (
                    "recent_ee_forcetorques",
                    "ee_forcetorques",
                ),
            )

            if (
                force_torque is not None
                and force_torque.size >= 6
            ):
                if force is None:
                    force = force_torque[:3]

                if torque is None:
                    torque = force_torque[3:6]

        if force is not None:
            _add_xyz_properties(
                properties,
                "recent_ee_force",
                force,
            )

        if torque is not None:
            _add_xyz_properties(
                properties,
                "recent_ee_torque",
                torque,
            )

        return properties

